# 自分自身に変換するエントリ (ノイズ) を除去
_SC_TO_JP = {k: v for k, v in _SC_TO_JP.items() if k != v}

# 1文字置換は translate で高速化
_SC_TRANS = str.maketrans(_SC_TO_JP)


# ---- custom_dict.txt のホットリロード ----------------------
def _load_custom_dict():
    """custom_dict.txt を読み込み (multi_dict, single_dict) を返す。
    ファイルの mtime を見て変更時のみ再読込 (ホットリロード)。"""
    if not os.path.isfile(_CUSTOM_PATH):
        return {}, {}

    try:
        mtime = os.path.getmtime(_CUSTOM_PATH)
    except OSError:
        return {}, {}

    cached = _CUSTOM_CACHE.get(_CUSTOM_PATH)
    if cached and cached[0] == mtime:
        return cached[1], cached[2]

    multi  = {}   # 2文字以上 (str.replace で適用)
    single = {}   # 1文字 (translate で適用)

    try:
        with open(_CUSTOM_PATH, "r", encoding="utf-8") as f:
            for raw in f:
                line = raw.split("#", 1)[0].strip()
                if not line or "=" not in line:
                    continue
                src, dst = line.split("=", 1)
                src, dst = src.strip(), dst.strip()
                if not src or not dst or src == dst:
                    continue
                if len(src) == 1 and len(dst) == 1:
                    single[src] = dst
                else:
                    multi[src] = dst
    except OSError:
        return {}, {}

    _CUSTOM_CACHE[_CUSTOM_PATH] = (mtime, multi, single)
    return multi, single


# ---- 公開 API ----------------------------------------------
def japanize(text: str) -> str:
    """OCR 出力に混入する中国漢字だけを日本語の漢字に変換する。
    日本語として正しい文字には一切手を加えない。"""
    if not text:
        return text

    # 1) 組み込みテーブル (1文字置換)
    text = text.translate(_SC_TRANS)

    # 2) ユーザー追加 (custom_dict.txt)
    multi, single = _load_custom_dict()
    for src, dst in multi.items():
        if src in text:
            text = text.replace(src, dst)
    if single:
        text = text.translate(str.maketrans(single))

    return text
